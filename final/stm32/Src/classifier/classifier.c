static float classifier_tree_predict_class1(uint32_t tree_index,
                                             const float scaled_features[CLASSIFIER_NUM_FEATURES]) {
  const uint16_t base = tree_offsets[tree_index];
  uint16_t node = 0U;

  while (node_left[base + node] >= 0) {
    const uint16_t index = (uint16_t)(base + node);
    const int8_t feature = node_feature[index];

    if (scaled_features[(uint8_t)feature] <= node_threshold[index]) {
      node = (uint16_t)node_left[index];
    } else {
      node = (uint16_t)node_right[index];
    }
  }

  return node_value_class1[base + node];
}

float classifier_predict_proba_class1(const float features[CLASSIFIER_NUM_FEATURES]) {
  float scaled_features[CLASSIFIER_NUM_FEATURES];
  float probability_sum = 0.0f;

  for (uint32_t i = 0U; i < CLASSIFIER_NUM_FEATURES; ++i) {
    scaled_features[i] = (features[i] - scaler_mean[i]) / scaler_scale[i];
  }

  for (uint32_t tree = 0U; tree < CLASSIFIER_NUM_TREES; ++tree) {
    probability_sum += classifier_tree_predict_class1(tree, scaled_features);
  }

  return probability_sum / (float)CLASSIFIER_NUM_TREES;
}

void classifier_predict_proba(const float features[CLASSIFIER_NUM_FEATURES],
                              float probabilities[CLASSIFIER_NUM_CLASSES]) {
  const float class1 = classifier_predict_proba_class1(features);

  probabilities[0] = 1.0f - class1;
  probabilities[1] = class1;
}

int32_t classifier_predict(const float features[CLASSIFIER_NUM_FEATURES]) {
  return (classifier_predict_proba_class1(features) > 0.5f) ? 1 : 0;
}
